//go:build ignore

// gen-go-notices writes the license and notice texts of every Go module that
// is compiled into the local-eml binary, for each release platform, to
// web/third-party/go-notices.txt. The web build folds that file into
// THIRD_PARTY_NOTICES.txt, which the binary embeds and the release attaches.
//
// Run from the repository root after changing go.mod:
//
//	go run scripts/gen-go-notices.go
//
// CI runs it with -check and fails when the committed file is stale.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	pkg = "./cmd/local-eml"
	out = "web/third-party/go-notices.txt"
)

// Every GOOS/GOARCH the release workflow builds. Some modules (wincred,
// godbus, go-uring) only link on one platform; the notices cover the union.
var platforms = [][2]string{
	{"linux", "amd64"}, {"linux", "arm64"},
	{"darwin", "amd64"}, {"darwin", "arm64"},
	{"windows", "amd64"}, {"windows", "arm64"},
}

var noticeFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|patents|unlicense)([.-].*)?$`)

type module struct {
	Path    string
	Version string
	Dir     string
}

func main() {
	check := flag.Bool("check", false, "exit 1 if "+out+" is out of date instead of writing it")
	flag.Parse()

	mods := map[string]module{}
	for _, p := range platforms {
		for _, m := range listModules(p[0], p[1]) {
			mods[m.Path] = m
		}
	}

	var b bytes.Buffer
	b.WriteString("Go modules compiled into the local-eml binary\n")
	b.WriteString("(generated by scripts/gen-go-notices.go; do not edit)\n")

	goroot := strings.TrimSpace(run(nil, "go", "env", "GOROOT"))
	writeGroup(&b, []string{"The Go standard library and runtime (https://go.dev)"}, readNotices(goroot))

	// Modules that ship byte-identical notice files (the AWS SDK's many
	// sub-modules) share one entry instead of repeating the Apache text.
	type group struct {
		names []string
		files []noticeText
	}
	groups := map[string]*group{}
	var order []string
	paths := make([]string, 0, len(mods))
	for p := range mods {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		m := mods[p]
		files := readNotices(m.Dir)
		if len(files) == 0 {
			fail("%s %s has no LICENSE/NOTICE file in %s", m.Path, m.Version, m.Dir)
		}
		h := sha256.New()
		for _, f := range files {
			fmt.Fprintf(h, "%s\x00%s\x00", f.name, f.text)
		}
		key := string(h.Sum(nil))
		g, ok := groups[key]
		if !ok {
			g = &group{files: files}
			groups[key] = g
			order = append(order, key)
		}
		g.names = append(g.names, m.Path+" "+m.Version)
	}
	for _, k := range order {
		writeGroup(&b, groups[k].names, groups[k].files)
	}

	if *check {
		cur, _ := os.ReadFile(out)
		if !bytes.Equal(cur, b.Bytes()) {
			fail("%s is out of date; run: go run scripts/gen-go-notices.go", out)
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		fail("%v", err)
	}
	if err := os.WriteFile(out, b.Bytes(), 0o644); err != nil {
		fail("%v", err)
	}
	fmt.Printf("wrote %s: %d modules, %d bytes\n", out, len(mods), b.Len())
}

func listModules(goos, goarch string) []module {
	env := append(os.Environ(), "GOOS="+goos, "GOARCH="+goarch, "CGO_ENABLED=0")
	outp := run(env, "go", "list", "-deps", "-json=Standard,Module", pkg)
	dec := json.NewDecoder(strings.NewReader(outp))
	var mods []module
	for dec.More() {
		var p struct {
			Standard bool
			Module   *struct {
				Path    string
				Version string
				Dir     string
				Main    bool
				Replace *struct{ Dir string }
			}
		}
		if err := dec.Decode(&p); err != nil {
			fail("go list: %v", err)
		}
		if p.Standard || p.Module == nil || p.Module.Main {
			continue
		}
		m := module{Path: p.Module.Path, Version: p.Module.Version, Dir: p.Module.Dir}
		if p.Module.Replace != nil && p.Module.Replace.Dir != "" {
			m.Dir = p.Module.Replace.Dir
		}
		mods = append(mods, m)
	}
	return mods
}

type noticeText struct{ name, text string }

func readNotices(dir string) []noticeText {
	entries, err := os.ReadDir(dir)
	if err != nil {
		fail("%v", err)
	}
	var files []noticeText
	for _, e := range entries {
		if e.IsDir() || !noticeFile.MatchString(e.Name()) {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			fail("%v", err)
		}
		text := strings.ReplaceAll(string(data), "\r\n", "\n")
		files = append(files, noticeText{e.Name(), strings.TrimRight(text, "\n ")})
	}
	return files
}

func writeGroup(b *bytes.Buffer, names []string, files []noticeText) {
	b.WriteString("\n" + strings.Repeat("=", 80) + "\n")
	for _, n := range names {
		b.WriteString(n + "\n")
	}
	for _, f := range files {
		b.WriteString(strings.Repeat("-", 80) + "\n")
		b.WriteString(f.name + "\n\n" + f.text + "\n")
	}
}

func run(env []string, name string, args ...string) string {
	cmd := exec.Command(name, args...)
	cmd.Env = env
	cmd.Stderr = os.Stderr
	outp, err := cmd.Output()
	if err != nil {
		fail("%s %s: %v", name, strings.Join(args, " "), err)
	}
	return string(outp)
}

func fail(format string, a ...any) {
	fmt.Fprintf(os.Stderr, "gen-go-notices: "+format+"\n", a...)
	os.Exit(1)
}
